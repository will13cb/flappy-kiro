'use strict';
// Generates src/game-config.js from game-config.json.
// Usage: npm run sync-config

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const JSON_PATH = path.join(ROOT, 'game-config.json');
const OUT_PATH = path.join(ROOT, 'src', 'game-config.js');

// Pure: returns the full content of src/game-config.js.
// `json` is the parsed config object (a JSON string is also accepted).
function renderConfigScript(json) {
  const data = typeof json === 'string' ? JSON.parse(json) : json;
  const body = JSON.stringify(data, null, 2);
  return [
    '// GENERATED by scripts/sync-config.js from game-config.json. Do not edit.',
    '// Edit game-config.json, then run: npm run sync-config',
    '(function (root) {',
    '  root.GAME_CONFIG = ' + body.replace(/\n/g, '\n  ') + ';',
    "})(typeof window !== 'undefined' ? (window.FlappyKiro = window.FlappyKiro || {}) : module.exports);",
    '',
  ].join('\n');
}

function syncConfig() {
  const parsed = JSON.parse(fs.readFileSync(JSON_PATH, 'utf8'));
  fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
  fs.writeFileSync(OUT_PATH, renderConfigScript(parsed), 'utf8');
  return OUT_PATH;
}

if (require.main === module) {
  const out = syncConfig();
  console.log('Wrote ' + path.relative(ROOT, out));
}

module.exports = { renderConfigScript, syncConfig, JSON_PATH, OUT_PATH };
